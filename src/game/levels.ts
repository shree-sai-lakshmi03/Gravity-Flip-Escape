function normalize(rows: string[]): string[] {
  const inner = rows
    .slice(0, INNER_H)
    .map((r) => (r + ".".repeat(INNER_W)).slice(0, INNER_W));
  while (inner.length < INNER_H) inner.push(".".repeat(INNER_W));
  const top = "#".repeat(INNER_W + 2);
  return [top, ...inner.map((r) => `#${r}#`), top];
}

